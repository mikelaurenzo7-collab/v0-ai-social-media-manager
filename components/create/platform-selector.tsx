import { cn } from '@/lib/utils'
import { PLATFORMS, SOCIAL_PLATFORM_IDS, type PlatformId } from '@/lib/constants/platforms'

interface PlatformSelectorProps {
  selected: PlatformId[]
  onChange: (platforms: PlatformId[]) => void
}

export function PlatformSelector({ selected, onChange }: PlatformSelectorProps) {
  const togglePlatform = (platformId: PlatformId) => {
    if (selected.includes(platformId)) {
      if (selected.length > 1) {
        onChange(selected.filter((p) => p !== platformId))
      }
    } else {
      onChange([...selected, platformId])
    }
  }

  return (
    <div className="flex flex-wrap gap-2">
      {SOCIAL_PLATFORM_IDS.map((id) => {
        const platform = PLATFORMS[id]
        const isSelected = selected.includes(id)
        return (
          <button
            key={id}
            type="button"
            aria-pressed={isSelected}
            onClick={() => togglePlatform(id)}
            className={cn(
              'flex items-center gap-2 rounded-full px-4 py-2 text-sm font-medium transition-all duration-200',
              isSelected
                ? 'text-white shadow-md scale-[1.02]'
                : 'bg-muted/60 text-muted-foreground border border-border/60 hover:bg-muted hover:text-foreground'
            )}
            style={
              isSelected
                ? { background: 'linear-gradient(135deg, #EA580C 0%, #DB2777 100%)', border: 'none' }
                : undefined
            }
          >
            <PlatformIcon platform={id} className="h-4 w-4" />
            {platform.shortName}
          </button>
        )
      })}
    </div>
  )
}

